import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
const html = await readFile('dist/index.html', 'utf8');
const script = html.match(/<script data-usfirst-boot>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script, '小启动脚本必须随HTML到达，不能再等boot.js网络请求');
assert.ok(!/<link[^>]+rel="stylesheet"/.test(html), '关键CSS不应再有阻塞网络请求');
assert.ok(Buffer.byteLength(html.slice(0,html.indexOf('id="boot-shell"')))<4096,'启动正文必须出现在HTML前4KB，不能被完整CSS挡在后面');
assert.ok(html.indexOf('</script>',html.indexOf('<script data-usfirst-boot>'))<12000,'内联快照启动必须在前12KB完成');
const headers = await readFile('dist/_headers', 'utf8');
const hash = createHash('sha256').update(script).digest('base64');
assert.ok(headers.includes("'sha256-" + hash + "'"), '内联脚本只能由精确构建hash授权');
assert.ok(!/script-src[^;\n]*unsafe-inline/.test(headers), '不能开放任意内联脚本');
const sw = await readFile('dist/sw.js', 'utf8');
const required = JSON.parse(sw.match(/const REQUIRED = (.+);/)[1]);
assert.ok(required.length <= 2, '安装必需文件不能包含懒加载表单及图片弹窗');
assert.ok(!required.some(path => /RequestForm|AppSheet|PhotoViewer/.test(path)));
const files = await readdir('dist/assets');
const main = html.match(/<script\b[^>]*src="\/assets\/([^\"]+\.js)"[^>]*>/)?.[1];
assert.ok(main && files.includes(main));
const js = await readFile('dist/assets/' + main);
assert.ok(gzipSync(js).length < 85000, '首屏脚本压缩后应低于85KB性能预算');
assert.ok(!js.toString().includes('react-router'), '单生产页面不应带整套路由实现');
console.log(JSON.stringify({ ok: true, checks: 10, criticalRequests: 2, jsBytes: js.length, jsGzipBytes: gzipSync(js).length, htmlGzipBytes: gzipSync(html).length, installRequired: required.length }));
